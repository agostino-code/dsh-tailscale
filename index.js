const STATE_PATH = '/api/dsh-tailscale/state'
const ROTATE_PATH = '/api/dsh-tailscale/rotate'

/**
 * Arms lazy WebSocket compression hook on DSH /api/remote.mux.
 * @param scope - Plugin context.
 * @param config - Normalized config.
 * @returns `{ armed }` or undefined if disabled.
 */
function armWebSocketCompression(scope, config) {
  if (!config.websocketCompression) return undefined
  return {
    armed: true,
    /**
     * Invoked once on the first handshake; no-op thereafter.
     * @returns boolean indicating if patch succeeded.
     */
    armOnce() {
      const result = installWebSocketCompression(scope, config)
      return result?.enabled === true
    },
  }
}

/**
 * Resolves the exact `ws` module instance used by DSH host.
 * Traverses DSH package anchors in app.asar to guarantee prototype sharing.
 * @returns `ws` module or undefined.
 */
function resolveHostWebSocket() {
  const anchors = []
  const resources = process.resourcesPath
  if (typeof resources === 'string' && resources !== '') {
    anchors.push(join(resources, 'app.asar', 'dsh', 'index.js'))
    anchors.push(join(resources, 'app.asar', 'dsh', 'node_modules', '@deepseek-ai', 'dsh-api-gateway', 'lib', 'index.js'))
  }
  anchors.push(import.meta.url)

  for (const anchor of anchors) {
    try {
      const ws = createRequire(anchor)('ws')
      if (ws?.WebSocketServer?.prototype !== undefined) return ws
    } catch {
      // try next anchor
    }
  }
  return undefined
}

/**
 * Enables permessage-deflate compression on DSH's /api/remote.mux WebSocket.
 * Patches handleUpgrade to ensure options apply synchronously without race conditions.
 * @param scope - Plugin context.
 * @param config - Normalized config.
 * @returns `{ enabled }` or undefined if skipped.
 */
function installWebSocketCompression(scope, config) {
  if (!config.websocketCompression) return undefined
  const ws = resolveHostWebSocket()
  if (ws === undefined) return undefined
  const proto = ws?.WebSocketServer?.prototype
  if (proto === undefined || typeof proto.handleUpgrade !== 'function') return undefined
  if (proto.handleUpgrade.__dshTailscalePatched === true) {
    return { enabled: true, alreadyPatched: true }
  }

  const original = proto.handleUpgrade
  const patched = function patchedHandleUpgrade(req, socket, head, callback) {
    if (this.options !== undefined && this.options.perMessageDeflate === false) {
      this.options.perMessageDeflate = {
        threshold: 1024,
        serverNoContextTakeover: true,
        clientNoContextTakeover: true,
      }
    }
    return original.call(this, req, socket, head, callback)
  }
  patched.__dshTailscalePatched = true
  proto.handleUpgrade = patched

  scope.effect(
    () => () => {
      if (proto.handleUpgrade === patched) proto.handleUpgrade = original
    },
    'dsh-tailscale: websocket compression',
  )
  scope.logger.info('dsh-tailscale: enabled permessage-deflate on DSH WebSocket')
  return { enabled: true }
}

/**
 * Installs the lazy WebSocket compression hook on the host's HTTP server.
 *
 * The hook is armed on the first `upgrade` event (the first client that opens the
 * `/api/remote.mux` socket), so boot pays nothing and the `ws` module is only
 * resolved when compression is actually needed. When the HTTP server is not
 * reachable through the `webServer` service, it falls back to patching immediately.
 *
 * @param scope - Plugin context that owns the `webServer` service.
 * @param config - Normalized config.
 * @returns `{ armed }` or undefined when disabled or unsupported.
 */
function setupWebSocketCompression(scope, config) {
  const webServer = scope.get('webServer', false)
  if (webServer === undefined) return undefined

  let websocketPatch = armWebSocketCompression(scope, config)
  if (websocketPatch === undefined) return undefined

  const raw = webServer.server
  if (raw !== undefined && typeof raw.prependListener === 'function') {
    const onUpgrade = () => {
      try {
        websocketPatch.armOnce()
      } catch (error) {
        scope.logger.warn(`dsh-tailscale: failed enabling WebSocket compression: ${error?.message ?? error}`)
      } finally {
        raw.removeListener('upgrade', onUpgrade)
      }
    }
    raw.prependListener('upgrade', onUpgrade)
    scope.effect(
      () => () => {
        try {
          raw.removeListener('upgrade', onUpgrade)
        } catch {
          /* server may be closed on unload */
        }
      },
      'dsh-tailscale: websocket compression trigger',
    )
  } else {
    websocketPatch = installWebSocketCompression(scope, config)
  }
  return websocketPatch
}

/** Record key in credentials for browser session signing secret. */
const AUTH_RECORD_KEY = 'client-connection/browser-session'
/** Session secret byte length matching client-connection SECRET_BYTES. */
const SESSION_SECRET_BYTES = 32
/** Record format version matching STORED_SECRET_VERSION. */
const STORED_SECRET_VERSION = 1

/** Extracts normalized authority from Host header. */
function hostAuthority(headers) {
  const host = headers?.get?.('host')
  if (typeof host !== 'string' || host === '') return undefined
  try {
    return new URL(`http://${host}`).host
  } catch {
    return undefined
  }
}

/**
 * Rotates the signing secret for DSH browser session cookies, revoking all active sessions.
 * Updates both the persistent credentials record and the active live `browserAuth.secret`.
 * @param scope - Context with connection and credentials services.
 * @returns Buffer of new secret bytes.
 */
async function rotateSessionSecret(scope) {
  const credentials = scope.get('credentials', false)
  if (credentials === undefined || typeof credentials.modifyRecord !== 'function') {
    throw new Error('Cannot read the credentials service, so active sessions cannot be revoked')
  }
  const connection = scope.get('connection', false)
  if (connection?.browserAuth === undefined) {
    throw new Error('Cannot read connection.browserAuth, so active sessions cannot be revoked')
  }

  const secret = randomBytes(SESSION_SECRET_BYTES).toString('base64url')
  const written = await credentials.modifyRecord(AUTH_RECORD_KEY, () =>
    Promise.resolve({
      kind: 'grant',
      payload: { version: STORED_SECRET_VERSION, secret },
    }),
  )

  if (written?.payload?.secret !== secret) {
    throw new Error('Session secret write failed (credentials record not updated)')
  }

  connection.browserAuth.secret = Buffer.from(secret, 'base64url')
  return connection.browserAuth.secret
}

/**
 * Constructs the state response object for management endpoints.
 * @param config - Normalized config.
 * @param runtime - Active runtime state.
 */
function statePayload(config, runtime) {
  const state = runtime.state
  return {
    ok: true,
    enabled: config.enabled,
    phase: runtime.phase,
    error: runtime.error ?? null,
    canRotate: config.enabled && config.loginRoute && runtime.phase === 'ready',
    revokesSessions: config.enabled && config.loginRoute && config.revokeSessionsOnRotate,
    plainUrl: state?.plainUrl ?? null,
    loginUrl: state?.loginUrl ?? null,
    authority: state?.authority ?? null,
    dnsName: state?.dnsName ?? null,
    httpsPort: state?.httpsPort ?? config.httpsPort,
    cookieMaxAgeDays: state?.cookieMaxAgeDays ?? config.cookieMaxAgeDays,
    updatedAt: state?.updatedAt ?? null,
  }
}

/**
 * Registers (or replaces) the persistent login route on the web server.
 * @param runtime - Active runtime state.
 * @param connection - Connection service.
 * @param config - Normalized config.
 * @param authority - `<dnsName>:<httpsPort>`.
 * @param secret - Secret string.
 * @returns New path string or undefined.
 */
function installLoginRoute(runtime, connection, config, authority, secret) {
  const webScope = runtime.webScope
  if (webScope === undefined) return undefined
  const webServer = webScope.get('webServer')
  if (webServer === undefined) return undefined

  runtime.login?.dispose?.()
  runtime.login = undefined

  const path = `/remote/${secret}`
  const dispose = webScope.effect(
    () =>
      webServer.register({
        kind: 'exact',
        path,
        handler: (req, res) => {
          if (req.method !== 'GET' && req.method !== 'HEAD') {
            res.writeHead(405)
            res.end()
            return
          }
          const minted = mintSessionCookie(connection, authority, config.cookieMaxAgeDays * 86400000)
          if (minted !== undefined) {
            res.writeHead(302, {
              location: `https://${authority}/`,
              'set-cookie': sessionCookieHeader(minted),
              'cache-control': 'no-store',
              'referrer-policy': 'no-referrer',
            })
            res.end()
            return
          }
          res.writeHead(302, {
            location: runtime.handoffUrl ?? `https://${authority}/`,
            'cache-control': 'no-store',
            'referrer-policy': 'no-referrer',
          })
          res.end()
        },
      }),
    'dsh-tailscale: login route',
  )

  runtime.login = { secret, path, dispose }
  return path
}

/**
 * Rotates login secret: generates new secret, revokes active sessions if configured,
 * replaces login route, updates persisted state, and re-issues cookie to requesting authority.
 */
async function rotateLoginSecret(scope, config, runtime, deps = REAL_DEPS, requestingAuthority) {
  if (!config.loginRoute) throw new Error('The login route is disabled (loginRoute=false), so there is no secret to rotate')
  const state = runtime.state
  if (state === undefined) throw new Error('Remote access is not ready yet, try again later')

  const connection = scope.get('connection', false)

  if (config.revokeSessionsOnRotate) await rotateSessionSecret(scope)

  const secret = randomBytes(24).toString('base64url')
  const loginPath = installLoginRoute(runtime, connection, config, state.authority, secret)
  if (loginPath === undefined) throw new Error('webServer is unavailable, so the secret cannot be rotated')

  const loginUrl = `https://${state.authority}${loginPath}`
  let handoffUrl = state.plainUrl
  try {
    handoffUrl = connection?.authenticatedUrl?.(state.plainUrl) ?? state.plainUrl
  } catch {
    handoffUrl = state.plainUrl
  }

  const next = {
    ...state,
    url: handoffUrl,
    loginUrl,
    loginPath,
    loginSecret: secret,
    updatedAt: new Date().toISOString(),
  }
  await deps.persistState(scope, next)
  runtime.state = next
  runtime.handoffUrl = handoffUrl
  if (runtime.undo !== undefined) runtime.undo.loginPath = loginPath

  // Re-issue cookie to the requesting authority so the current device stays signed in.
  let stayedSignedIn = false
  if (config.revokeSessionsOnRotate && typeof requestingAuthority === 'string' && requestingAuthority !== '') {
    const minted = mintSessionCookie(connection, requestingAuthority, config.cookieMaxAgeDays * 86400000)
    if (minted !== undefined) stayedSignedIn = true
    return {
      loginUrl,
      loginPath,
      updatedAt: next.updatedAt,
      revokesSessions: true,
      stayedSignedIn,
      cookie: minted === undefined ? null : sessionCookieHeader(minted),
    }
  }

  return { loginUrl, loginPath, updatedAt: next.updatedAt, revokesSessions: config.revokeSessionsOnRotate, stayedSignedIn }
}

/**
 * Registers management endpoints on connection.fetch.
 * @param scope - Context with connection service.
 * @param config - Normalized config.
 * @param runtime - Active runtime state.
 */
function registerAdminRoutes(scope, config, runtime, deps = REAL_DEPS) {
  const connection = scope.get('connection', false)
  const routes = connection?.fetch
  if (routes === undefined) return

  const json = (payload, status = 200, extraHeaders) =>
    new Response(JSON.stringify(payload), {
      status,
      headers: {
        'content-type': 'application/json; charset=utf-8',
        'cache-control': 'no-store',
        ...(extraHeaders ?? {}),
      },
    })

  scope.effect(
    () =>
      routes.register({
        path: STATE_PATH,
        methods: ['GET'],
        requestBody: 'buffered',
        fetch: () => Promise.resolve(json(statePayload(config, runtime))),
      }),
    'dsh-tailscale: state route',
  )

  scope.effect(
    () =>
      routes.register({
        path: ROTATE_PATH,
        methods: ['POST'],
        requestBody: 'buffered',
        fetch: async (request) => {
          try {
            const result = await rotateLoginSecret(scope, config, runtime, deps, hostAuthority(request?.headers))
            const cookie = typeof result.cookie === 'string' ? { 'set-cookie': result.cookie } : undefined
            const { cookie: _omitted, ...payload } = result
            return json({ ok: true, ...payload }, 200, cookie)
          } catch (error) {
            return json({ ok: false, error: String(error?.message ?? error) }, 409)
          }
        },
      }),
    'dsh-tailscale: rotate route',
  )
}

/**
 * Initializes fresh runtime state object for the session.
 * @param undo - Rollback journal for the current run.
 */
function freshRuntime(undo) {
  return {
    phase: 'starting',
    error: undefined,
    /** Latest persisted state snapshot. */
    state: undefined,
    /** webServer scope where login route was mounted. */
    webScope: undefined,
    /** Active login route descriptor `{ secret, path, dispose }`. */
    login: undefined,
    /** Tokenized handoff URL used for fallback redirect. */
    handoffUrl: undefined,
    undo,
  }
}

/**
 * Plugin entry point.
 * @param {import('@deepseek-ai/cordis').Context} ctx - Plugin context.
 * @param {unknown} rawConfig - Config declared on this row.
 */
export function apply(ctx, rawConfig) {
  const config = normalizeConfig(rawConfig)

  ctx.inject(['connection'], (scope) => {
    if (scope.get('connection') === undefined) return

    const undo = {
      trustedHost: undefined,
      createdRoute: false,
      startedTailscale: false,
      binary: undefined,
      loginPath: undefined,
      disposed: false,
    }
    const runtime = freshRuntime(undo)

    if (!config.enabled) {
      runtime.phase = 'disabled'
      ctx.logger.info('dsh-tailscale: enabled=false, serving status only, taking no action')
      registerAdminRoutes(scope, config, runtime)
      return
    }

    registerAdminRoutes(scope, config, runtime)

    // WebSocket compression is armed lazily on the first handshake, so boot pays nothing.
    scope.inject(['webServer'], (webScope) => {
      const patch = setupWebSocketCompression(webScope, config)
      if (patch !== undefined) {
        ctx.logger.info('dsh-tailscale: WebSocket compression armed (lazy, first handshake)')
      }
    })

    scope.effect(() => async () => {
      if (undo.disposed) return
      undo.disposed = true
      if (!config.teardownOnExit) return
      await Promise.allSettled([teardown(scope, config, undo)])
    }, 'dsh-tailscale: teardown')

    setup(scope, config, undo, REAL_DEPS, runtime).catch((error) => {
      runtime.phase = 'error'
      runtime.error = String(error?.message ?? error)
      scope.logger.warn(`dsh-tailscale: startup failed: ${runtime.error}`)
    })
  })
}

