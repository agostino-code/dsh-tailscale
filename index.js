/** Startup: brings up tailscale -> provisions serve route -> trusts authority -> logs access URLs. */
async function setup(scope, config, undo, deps = REAL_DEPS, runtime = freshRuntime(undo)) {
  const logger = scope.logger
  runtime.undo = undo
  runtime.phase = 'starting'
  runtime.error = undefined

  const binary = await deps.resolveBinary(scope, config.binaryPath)
  if (binary === undefined) {
    runtime.phase = 'unavailable'
    runtime.error = 'Cannot find tailscale binary'
    logger.warn('dsh-tailscale: cannot find tailscale binary; please install Tailscale or specify path via config.binaryPath')
    return
  }
  undo.binary = binary

  let status = await deps.readStatus(binary)
  const wasRunning = status?.BackendState === 'Running'

  const running = await ensureRunning(binary, config, deps, logger, undo)
  if (!running) {
    runtime.phase = 'unavailable'
    runtime.error = 'tailscale is not running'
    return
  }
  if (!wasRunning) status = await deps.readStatus(binary)

  const dnsName = dnsNameOf(status)
  if (dnsName === undefined) {
    runtime.phase = 'unavailable'
    runtime.error = 'Cannot read tailnet DNS name'
    logger.warn('dsh-tailscale: cannot read tailnet DNS name, skipping Serve configuration')
    return
  }

  const port = await deps.waitForPort(scope)
  if (port === undefined) {
    runtime.phase = 'unavailable'
    runtime.error = 'Timeout waiting for DSH Web port'
    logger.warn('dsh-tailscale: timeout waiting for DSH Web port, skipping Serve configuration')
    return
  }

  const target = `http://127.0.0.1:${String(port)}`
  const authority = `${dnsName}:${String(config.httpsPort)}`

  if (config.serveOnStart) {
    const serveStatus = await deps.readServeStatus(binary)
    const state = classifyServe(serveStatus, config.httpsPort, target)
    if (state.kind === 'conflict') {
      runtime.phase = 'error'
      runtime.error = `Conflict with existing Serve config on port ${String(config.httpsPort)} (${state.reason})`
      logger.warn(`dsh-tailscale: conflict with existing Serve config on port ${String(config.httpsPort)} (${state.reason})`)
      return
    }
    if (state.kind === 'exact') {
      logger.info(`dsh-tailscale: ${authority} already proxies ${target}, claiming route (will teardown on exit)`)
      undo.createdRoute = true
    } else {
      if (state.kind === 'stale') {
        logger.info(`dsh-tailscale: claiming stale route ${state.authority} (previously proxied ${state.previousProxy})`)
      }
      const serve = await deps.run(binary, ['serve', '--bg', `--https=${String(config.httpsPort)}`, target], SETUP_TIMEOUT_MS)
      if (!serve.ok) {
        const detail = (serve.stderr || serve.stdout).trim().slice(0, 300)
        runtime.phase = 'error'
        runtime.error = detail === '' ? 'Failed to configure Serve' : detail
        logger.warn(
          `dsh-tailscale: failed configuring Serve: ${detail}; ` +
            'if HTTPS cert error, please enable HTTPS Certificates in Tailscale Admin Console',
        )
        return
      }
      undo.createdRoute = true
    }
  }

  if (config.trustedHosts) {
    const trusted = connectionTrustedHosts(scope)
    if (trusted === undefined) {
      logger.warn('dsh-tailscale: cannot read connection.trustedHosts, remote RPC will be rejected with 403')
    } else if (!trusted.includes(authority)) {
      trusted.push(authority)
      undo.trustedHost = authority
      logger.info(`dsh-tailscale: added ${authority} to /api trusted hosts list`)
    }
  }

  const plainUrl = `https://${authority}/`
  const connection = scope.get('connection')

  // Extend cookie validity to configured duration (default 10 years).
  if (config.cookieMaxAgeDays > 0) {
    const maxAgeMilliseconds = config.cookieMaxAgeDays * 86400000
    const auth = connection?.browserAuth
    if (auth !== undefined && Number.isSafeInteger(Date.now() + maxAgeMilliseconds)) {
      auth.maxAgeMilliseconds = maxAgeMilliseconds
      logger.info(`dsh-tailscale: set login cookie max age to ${String(config.cookieMaxAgeDays)} days`)
    } else {
      logger.warn('dsh-tailscale: cannot read connection.browserAuth, retaining DSH default cookie max age')
    }
  }

  let handoffUrl = plainUrl
  try {
    handoffUrl = connection?.authenticatedUrl?.(plainUrl) ?? plainUrl
  } catch {
    handoffUrl = plainUrl
  }
  runtime.handoffUrl = handoffUrl

  let loginUrl = plainUrl
  let loginPath
  if (config.loginRoute) {
    const secret = await deps.ensureLoginSecret(scope, config, deps)
    loginPath = `/remote/${secret}`
    loginUrl = `https://${authority}${loginPath}`
    undo.loginPath = loginPath
    scope.inject(['webServer'], (webScope) => {
      runtime.webScope = webScope
      installLoginRoute(runtime, connection, config, authority, secret)
    })
  }

  const loginSecret = loginPath === undefined ? undefined : loginPath.slice('/remote/'.length)
  const snapshot = {
    url: handoffUrl,
    loginUrl,
    loginPath,
    loginSecret,
    plainUrl,
    authority,
    dnsName,
    httpsPort: config.httpsPort,
    target,
    cookieMaxAgeDays: config.cookieMaxAgeDays,
    updatedAt: new Date().toISOString(),
    stateFile: config.stateFile,
  }
  await deps.persistState(scope, snapshot)
  runtime.state = snapshot
  runtime.phase = 'ready'
  runtime.error = undefined

  logger.info(`dsh-tailscale: mobile address ${plainUrl}`)
  if (loginUrl !== plainUrl) {
    logger.info(`dsh-tailscale: persistent mobile login URL ${loginUrl}`)
  }
  logger.info(`dsh-tailscale: one-time token URL ${handoffUrl}`)
  deps.announce?.(plainUrl, loginUrl, handoffUrl)
}

/** Default console announcement for stdout. */
function announce(plainUrl, loginUrl, handoffUrl) {
  console.log(`dsh-tailscale: ${plainUrl}`)
  if (loginUrl !== plainUrl) console.log(`dsh-tailscale (persistent login): ${loginUrl}`)
  console.log(`dsh-tailscale (one-time token): ${handoffUrl}`)
}

/**
 * Polls for `webServer.port` readiness.
 */
async function waitForPort(scope, timeoutMs = 8000) {
  const deadline = Date.now() + timeoutMs
  for (;;) {
    const port = scope.get('webServer')?.port
    if (Number.isInteger(port) && port > 0) return port
    if (Date.now() >= deadline) return undefined
    await new Promise((resolve) => setTimeout(resolve, 100))
  }
}

/** Retrieves mutable trustedHosts array from connection service. */
function connectionTrustedHosts(scope, strict = true) {
  const connection = scope.get('connection', strict)
  const trusted = connection?.trustedHosts
  return Array.isArray(trusted) ? trusted : undefined
}

/** Teardown: rolls back side-effects according to undo journal. Idempotent and concurrency-safe. */
async function teardown(scope, config, undo, deps = REAL_DEPS) {
  const logger = scope.logger
  try {
    if (undo.trustedHost !== undefined) {
      // strict=false: connection fiber may no longer be active during teardown, but still remove authority.
      const trusted = connectionTrustedHosts(scope, false)
      if (trusted !== undefined) {
        const at = trusted.indexOf(undo.trustedHost)
        if (at !== -1) trusted.splice(at, 1)
      }
      undo.trustedHost = undefined
    }
  } catch {
    /* context may be tearing down */
  }

  if (!undo.createdRoute && !undo.startedTailscale) return

  const binary = undo.binary ?? (await deps.resolveBinary(scope, config.binaryPath))
  if (binary === undefined) return

  if (undo.createdRoute) {
    undo.createdRoute = false
    const off = await deps.run(binary, ['serve', `--https=${String(config.httpsPort)}`, 'off'], TEARDOWN_TIMEOUT_MS)
    if (off.ok) logger.info(`dsh-tailscale: revoked Serve route on port ${String(config.httpsPort)}`)
    else logger.warn(`dsh-tailscale: failed revoking Serve route: ${(off.stderr || off.stdout).trim().slice(0, 200)}`)
  }

  if (undo.startedTailscale) {
    undo.startedTailscale = false
    const down = await deps.run(binary, ['down'], TEARDOWN_TIMEOUT_MS)
    if (down.ok) logger.info('dsh-tailscale: disconnected tailscale (was started by DSH)')
    else logger.warn(`dsh-tailscale: tailscale down failed: ${(down.stderr || down.stdout).trim().slice(0, 200)}`)
  }
}

