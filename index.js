/**
 * dsh-tailscale — Exposes the local DSH Web GUI over Tailscale Serve to your tailnet,
 * enabling mobile access across any network; cleanly tears down the route when DSH exits.
 *
 * Design insights:
 *
 * 1. `tailscale serve` preserves the client's Host header (verified: requests via tailnet
 *    contain `host: <dnsName>:7259`). DSH's `/api` fence (`isTrustedApiRequest`) requires
 *    the Host to be loopback or explicitly listed in `trustedHosts`; otherwise requests fail with 403.
 *    Therefore, the plugin pushes `<dnsName>:<port>` into `connection.trustedHosts`.
 *
 * 2. `connection.trustedHosts` is a public mutable array on the service, read on every request,
 *    so pushing at runtime takes effect immediately without altering profile cordis.yml.
 *
 * 3. Connecting seamlessly from mobile relies on one-time token links generated by
 *    `connection.authenticatedUrl(url)`: opening with `?token=` sets a 30-day HttpOnly cookie,
 *    allowing subsequent visits to be bookmarked directly.
 *
 * 4. Cleanup on exit is mounted on `ctx.effect(() => () => ...)`: this is the reliable teardown
 *    hook in Cordis. Cleanup must be idempotent and never reject (rejected disposers cause AggregateError).
 *
 * @module dsh-tailscale
 */

